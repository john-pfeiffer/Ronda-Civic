// Writes art-templates/: one file per puppet part, prop and backdrop, at the exact
// size the game expects, with joints marked. Run with: npm run art:templates
import { createServer } from 'vite';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { Resvg } from '@resvg/resvg-js';

const OUT = 'art-templates';
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const { RIGS } = await server.ssrLoadModule('/src/art/rigs.ts');
const { PROPS } = await server.ssrLoadModule('/src/art/props.ts');
const { BACKGROUNDS } = await server.ssrLoadModule('/src/art/backgrounds.ts');
const { partTemplateSvg, rigSheetSvg } = await server.ssrLoadModule('/src/art/templates.ts');

const png = (svg) => new Resvg(svg, { font: { loadSystemFonts: true } }).render().asPng();
const doc = (d, zoom) => `<svg xmlns="http://www.w3.org/2000/svg" width="${d.w * zoom}" height="${d.h * zoom}" viewBox="0 0 ${d.w} ${d.h}">${d.svg}</svg>`;

await rm(OUT, { recursive: true, force: true });
let files = 0;
const table = [];

for (const rig of Object.values(RIGS)) {
  const dir = `${OUT}/characters/${rig.id}`;
  await mkdir(dir, { recursive: true });
  for (const part of rig.parts) {
    // SVG: placeholder art and guides on separate layers. PNG: art only, plus a guide version to trace over.
    await writeFile(`${dir}/${part.id}.svg`, partTemplateSvg(rig, part, { guides: true }));
    await writeFile(`${dir}/${part.id}.png`, png(partTemplateSvg(rig, part, { guides: false })));
    await writeFile(`${dir}/${part.id}.guide.png`, png(partTemplateSvg(rig, part, { guides: true })));
    files += 3;
    table.push(`| ${rig.id} | \`${part.id}\` | ${part.w * 4} × ${part.h * 4} | ${part.pivot[0] * 4}, ${part.pivot[1] * 4} | ${part.parent ?? 'body root'} |`);
  }
  await writeFile(`${dir}/_all-parts.png`, png(rigSheetSvg(rig)));
  const json = {
    scale: rig.scale,
    parts: Object.fromEntries(rig.parts.map((p) => [p.id, { w: p.w, h: p.h, pivot: p.pivot, attach: p.attach, order: p.order }])),
  };
  await writeFile(`${dir}/rig.json`, JSON.stringify(json, null, 2) + '\n');
  files += 2;
}

for (const [folder, set, zoom] of [['props', PROPS, 2], ['backgrounds', BACKGROUNDS, 1]]) {
  await mkdir(`${OUT}/${folder}`, { recursive: true });
  for (const [name, def] of Object.entries(set)) {
    await writeFile(`${OUT}/${folder}/${name}.png`, png(doc(def, zoom)));
    files++;
  }
}

await writeFile(
  `${OUT}/PARTS.md`,
  `# Part list\n\nGenerated by \`npm run art:templates\`. Sizes are the template canvas in pixels (4 px per rig unit).\n\n` +
    `| Character | Part | Canvas (px) | Joint at (px) | Attached to |\n|---|---|---|---|---|\n${table.join('\n')}\n`,
);
await server.close();
console.log(`wrote ${files + 1} files to ${OUT}/`);
